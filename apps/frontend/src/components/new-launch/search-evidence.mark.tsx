'use client';

import type { FC } from 'react';
import { Status } from '@contentfactory/frontend/components/ui/surface';

/**
 * Ярлык «Взято из поиска» у элемента списка материала (`content-factory-next-
 * ec48.2`).
 *
 * 05.09.2026 владелец разрешил пускать в текст найденное поиском и просил
 * помечать его словами «взято из поиска», а не «не проверено». Пометка стоит
 * в трёх местах — в промпте, в записке под постом и здесь, у самой строки, —
 * и во всех трёх это одни и те же слова; иначе человек читает три разных
 * правила вместо одного.
 *
 * Собственной геометрии и собственных цветов здесь нет: это `Status` с тоном
 * `info`, тот же самый, каким витрина «Откуда факты» красит «Найдено
 * поиском». Совпадение не случайное — это одно и то же происхождение,
 * увиденное из двух мест, и оно должно узнаваться с одного взгляда. Токен
 * `label-sm` моноширинный, то есть ярлык читается как штамп, а не как
 * продолжение фразы рядом.
 */
export const SearchEvidenceMark: FC<{
  /**
   * Слово приходит снаружи: этот список уже переводится через `useT`, а
   * компонент не должен тащить за собой контекст перевода ради одной строки.
   */
  label: string;
}> = ({ label }) => <Status tone="info">{label}</Status>;
