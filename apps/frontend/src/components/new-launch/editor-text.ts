/**
 * Разметка коробок редактора → слова, которыми можно спрашивать.
 *
 * Одна функция на всех, кто задаёт вопрос о том, что человек уже написал:
 * «свои тексты по теме» и строка качества под редактором. Коробка хранит
 * HTML, а обе двери меряют текст, и второй такой же `replace(/<[^>]*>/g)`
 * рядом с первым разошёлся бы на первом же `&nbsp;`.
 *
 * Здесь нет ни одного импорта React нарочно: и разбор, и его границы
 * проверяются без документа.
 */
export const editorPlainText = (html: string | null | undefined): string =>
  String(html || '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
