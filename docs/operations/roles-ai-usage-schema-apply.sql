-- ДВА ФАЙЛА В ОДНОМ, И ПОРЯДОК МЕЖДУ НИМИ ОБЯЗАТЕЛЕН. Читайте раздел
-- «Добавление значения в существующее перечисление» в production-deploy.md
-- прежде, чем выполнять: часть А применяется ОТДЕЛЬНО и ПЕРВОЙ, часть Б —
-- обычным проверенным порядком. Одной командой их выполнять нельзя.
--
-- Почему так. Валидатор `validate-prisma-migration-sql.cjs` отклоняет
-- `ALTER TYPE ... ADD VALUE` в обоих режимах и никаким флагом его не впустить:
-- применение идёт одной транзакцией, а значение, добавленное транзакцией, в
-- ней же использовать нельзя. Пока это значение отсутствует в базе, `migrate
-- diff` печатает его, и валидатор отказывает **всему** diff — то есть часть Б
-- через него не пройдёт, пока не выполнена часть А.

-- ============================================================
-- ЧАСТЬ А. Отдельно, вне транзакции валидатора, ПЕРВОЙ.
-- ============================================================
-- Безопасно при работающем старом коде: пока значения нет ни у одной строки,
-- старый клиент Prisma его не встретит, а присвоить его умеет только новый.
-- `IF NOT EXISTS`, потому что этот оператор выполняется отдельной командой,
-- вне транзакции, и вручную. Без него повторный прогон — после обрыва связи,
-- после отката образа, при второй попытке выпуска — падает с `already exists`
-- и останавливает порядок на шаге, который на самом деле уже сделан.
ALTER TYPE "Role" ADD VALUE IF NOT EXISTS 'EDITOR';

-- ============================================================
-- ЧАСТЬ Б. Только после части А, обычным порядком раздела
-- «Если изменилась Prisma-схема»: migrate diff → отбор → валидатор
-- (--allow-table AiUsageRecord) → psql --single-transaction.
-- ============================================================
-- Три оператора ниже — это в точности то, что печатает `migrate diff` после
-- части А. Файл здесь для чтения и сверки; применять надо тот текст, который
-- напечатал diff на вашей базе, иначе валидатор откажет на посимвольном
-- сравнении.

-- AlterTable
ALTER TABLE "AiUsageRecord" ADD COLUMN     "userId" TEXT;

-- CreateIndex
CREATE INDEX "AiUsageRecord_organizationId_userId_createdAt_idx" ON "AiUsageRecord"("organizationId", "userId", "createdAt");

-- AddForeignKey
ALTER TABLE "AiUsageRecord" ADD CONSTRAINT "AiUsageRecord_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User"("id") ON DELETE SET NULL ON UPDATE CASCADE;
