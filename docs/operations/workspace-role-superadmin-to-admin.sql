-- Шаг данных, не схемы: членства области с ролью SUPERADMIN становятся ADMIN.
-- Решение владельца 04.09.2026 (content-factory-next-fn33.19): создатель
-- области — ADMIN, значение SUPERADMIN никому не выдаётся; в перечислении
-- оно остаётся ради совместимости с upstream и старых строк.
--
-- Применять ТОЛЬКО этот текст, дословно, через psql, никогда prisma db push.
-- Порядок:
--   1. счёт до:  SELECT count(*) FROM "UserOrganization" WHERE role = 'SUPERADMIN';
--   2. psql -v ON_ERROR_STOP=1 --single-transaction --file этот_файл
--   3. счёт после должен быть 0; число обновлённых строк записать в runbook.
-- Порядок обязателен: ТОЛЬКО ПОСЛЕ переключения образа этой волны, не раньше.
-- Здесь раньше стояло «порядок относительно образа безразличен» — это неправда.
-- На старом образе единственной защитой области от потери последнего
-- администратора была сама роль SUPERADMIN: она выдавалась ровно одному
-- членству и её нельзя было снять. Счёта администраторов там ещё нет — его
-- приносит эта волна (content-factory-next-fn33.19 в deleteTeamMember и
-- content-factory-next-fn33.108 в удалении аккаунта администратором
-- инстанса). Выполнить этот UPDATE на старом образе значит снять защиту до
-- того, как встанет заменяющая: между двумя моментами область можно оставить
-- без администратора, и обратного шага у этого нет.
-- Флаг User.isSuperAdmin (администратор инстанса) этим шагом не затрагивается.
--
-- Выполнено на боевой базе 04.09.2026 после переключения на выпуск
-- d782858045fa: строк SUPERADMIN до — 5, обновлено 5, после — 0.

UPDATE "UserOrganization" SET role = 'ADMIN' WHERE role = 'SUPERADMIN';
SELECT count(*) AS superadmin_left FROM "UserOrganization" WHERE role = 'SUPERADMIN';
