-- пять коротких полей на выходе — оплачивалась по цене написания черновика, а
-- потолок расходов включённого режима задавала самая дорогая операция
-- продукта. Рычага не было вовсе: имя модели читалось прямо в месте вызова,
-- поэтому никакая настройка его не двигала.
--
-- Две колонки, обе nullable и без значения по умолчанию, поэтому таблицы не
-- переписываются и окно простоя не нужно.
--
--   1. `AiProviderSetting.roleModels` (Json) — какая модель у какой роли,
--      в виде `{"classify": "…", "draft": "…"}`. Одна JSON-колонка, а не
--      колонка на роль и не таблица имён моделей в репозитории: ролей мало и
--      они наши, а имена моделей — арендатора, меняются каждые несколько
--      месяцев, и у арендатора на своём поставщике они такие, каких мы не
--      видели. Неизвестные ключи и негодные значения отбрасываются при
--      чтении (`libraries/nestjs-libraries/src/openai/ai.roles.ts`), поэтому
--      строка, написанная более старой или более новой сборкой, не приводит
--      к неудачной генерации.
--
--   2. `AiUsageRecord.role` (String) — что именно просили у модели, рядом с
--      тем, что делал продукт. Операция — единица счёта, роль — ось, по
--      которой настроена маршрутизация; для большинства дверей они совпадают
--      и намеренно не совпадают у `text_generation`, который покрывает и
--      черновик, и разбор голоса, и правку предложения.
--
-- Что происходит с существующими строками. Обе колонки получают NULL, и NULL
-- читается как «ничего не маршрутизировано» и «записано до ролей»: каждая
-- роль падает на `textModel`, то есть ровно то поведение, которое продукт имел
-- до этой задачи. Шага данных нет, обратного шага тоже: на старом образе
-- лишние nullable-колонки никому не мешают.
--
-- Индексов нет намеренно. По `roleModels` не ищут — её читают вместе со
-- строкой настройки. Разбивку расхода по ролям считает `groupBy` за период
-- одной области, и его обслуживает существующий
-- `AiUsageRecord_organizationId_usageMode_createdAt_idx`; заводить индекс под
-- экран настроек, который открывают несколько раз в месяц, значит платить
-- записью на каждой операции ИИ за чтение, которого почти нет.
--
-- `prisma migrate diff` против боевой базы печатает эти операторы вместе с
-- DROP TABLE на mastra_* таблицы, которых нет в schema.prisma. Их пропускает
-- validate-prisma-migration-sql.cjs (Mastra-owned target), но проверять
