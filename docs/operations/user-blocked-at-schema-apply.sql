-- Один столбец на User. Применять ТОЛЬКО этот текст, дословно.
--
-- Зачем: до `content-factory-next-fn33.66` заблокированный аккаунт и аккаунт,
-- ждущий одобрения, были одним и тем же состоянием — `activated = false`.
-- Заблокированный попадал на вкладку «Ожидает одобрения» с кнопкой
-- «Одобрить», и снятие блокировки выглядело как обычное одобрение заявки.
-- `blockedAt` — отметка времени блокировки: NULL у всех, кого не блокировали.
-- Блокировка её ставит, одобрение и разблокировка чистят.
--
-- Столбец nullable и без значения по умолчанию, поэтому оператор не переписывает
-- таблицу и не требует окна простоя. Индекс не нужен: по нему не ищут, его
-- читают вместе со строкой. Существующие строки получают NULL — то есть
-- «никогда не блокировался». Если на боевой базе есть выключенные аккаунты,
-- которых блокировали ДО применения этого столбца, они останутся в «Ожидает
-- одобрения»; разобрать их — отдельное решение владельца, не этот файл.
--
-- `prisma migrate diff` против боевой базы печатает этот оператор вместе с
-- DROP TABLE на mastra_* таблицы, которых нет в schema.prisma. Их пропускает
-- validate-prisma-migration-sql.cjs (Mastra-owned target), но проверять
-- каждый раз всё равно нужно: db push и полный вывод migrate diff сносят их
-- молча.
--
-- Порядок применения:
--   1. prisma migrate diff --from-url <DATABASE_URL>
--        --to-schema-datamodel schema.prisma --script
--   2. scripts/operations/validate-prisma-migration-sql.cjs --mode update
--        --allow-table User --diff <шаг 1> --selected этот_файл
--   3. psql -v ON_ERROR_STOP=1 --single-transaction --file this_file
--   4. Повторный migrate diff должен вернуть только mastra_* DROP TABLE.
--
-- Валидатор отвергает BEGIN/COMMIT как неизвестные операции схемы;
-- транзакционность обеспечивает флаг --single-transaction в psql.
--
-- Столбец добавлен в schema.prisma 04.09.2026. Применено: на стенде тем же
-- днём через psql; на боевой базе 04.09.2026 с разрешения владельца, до
-- переключения на выпуск d782858045fa (запись в production-deploy.md).

