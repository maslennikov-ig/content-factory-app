'use strict';

/**
 * Жирное: одна форма в хранении, разметка площадки — на выходе.
 *
 * `content-factory-next-97dq.2`, находка восьмого захода 18.09.2026: «в
 * адаптации есть звёздочки… Markdown-разметка не срабатывает». Модель писала
 * `**текст**` — так пишут все, — продукт клал это в пост как есть, и человек
 * читал звёздочки в вышедшем посте.
 *
 * Здесь судится таблица перевода целиком, потому что каждая её строка — это
 * отдельный способ опубликовать мусор: непарный маркер, пара через абзац,
 * угловая скобка внутри выделения и площадка, которая разметки не показывает.
 */

const { loadTypeScriptModule } = require('./helpers/load-tsx.cjs');

const { editorHtml, boldToStrong, stripBoldMarkers } = loadTypeScriptModule(
  'libraries/nestjs-libraries/src/content-intelligence/brief/editor-html.ts'
);

describe('редактор с тегами получает <strong>, а не звёздочки', () => {
  test('парное выделение внутри строки становится тегом', () => {
    expect(editorHtml('Комиссия выросла до **27,5%** с июля.', 'html')).toBe(
      '<p>Комиссия выросла до <strong>27,5%</strong> с июля.</p>'
    );
  });

  test('два выделения в абзаце переводятся оба', () => {
    expect(editorHtml('**Первое** и **второе**.', 'html')).toBe(
      '<p><strong>Первое</strong> и <strong>второе</strong>.</p>'
    );
  });

  test('непарный маркер снимается, а не публикуется', () => {
    expect(editorHtml('Осталась **одна звёздочка в тексте.', 'html')).toBe(
      '<p>Осталась одна звёздочка в тексте.</p>'
    );
    expect(editorHtml('Хвост текста**', 'html')).toBe('<p>Хвост текста</p>');
  });

  test('маркеры через абзац не растягивают выделение на полпоста', () => {
    expect(editorHtml('Начало **здесь\n\nи конец** там.', 'html')).toBe(
      '<p>Начало здесь</p><p>и конец там.</p>'
    );
  });

  test('маркеры через перевод строки внутри абзаца тоже не пара', () => {
    expect(editorHtml('Начало **здесь\nи конец** там.', 'html')).toBe(
      '<p>Начало здесь и конец там.</p>'
    );
  });

  test('угловые скобки и амперсанд внутри выделения экранируются', () => {
    expect(editorHtml('Правило **<b>a & b</b>** остаётся.', 'html')).toBe(
      '<p>Правило <strong>&lt;b&gt;a &amp; b&lt;/b&gt;</strong> остаётся.</p>'
    );
  });

  test('одиночная звёздочка в прозе остаётся собой', () => {
    expect(editorHtml('Цена 5 * 3 рубля, сноска * внизу.', 'html')).toBe(
      '<p>Цена 5 * 3 рубля, сноска * внизу.</p>'
    );
    // Звёздочка внутри пары делает её не парой: маркеры снимаются, текст цел.
    expect(editorHtml('Итог **5 * 3** рубля.', 'html')).toBe(
      '<p>Итог 5 * 3 рубля.</p>'
    );
  });

  test('список через дефис не теряет своих дефисов', () => {
    expect(editorHtml('- первое\n- второе', 'html')).toBe(
      '<p>- первое - второе</p>'
    );
  });
});

describe('редакторы без выделения получают чистый текст', () => {
  test('normal оставляет абзацы и снимает маркеры', () => {
    expect(editorHtml('**Жирное** начало.\n\nВторой абзац.', 'normal')).toBe(
      '<p>Жирное начало.</p><p>Второй абзац.</p>'
    );
  });

  test('none отдаёт текст без тегов и без маркеров', () => {
    expect(editorHtml('**Жирное** начало.\n\nВторой абзац.', 'none')).toBe(
      'Жирное начало.\n\nВторой абзац.'
    );
  });

  /**
   * `markdown` — единственная площадка, где `**текст**` и есть рабочая
   * разметка: там она написана на языке редактора, и снимать её значило бы
   * забрать у канала выделение, которое он показывает.
   */
  test('markdown оставляет пары себе', () => {
    expect(editorHtml('**Жирное** начало.', 'markdown')).toBe(
      '**Жирное** начало.'
    );
  });

  /**
   * Разбор корректности, P1-4: ветка `markdown` возвращала тело нетронутым, и
   * непарная звёздочка уходила в Discord, Medium, Dev.to, Hashnode и Whop
   * байт в байт. Хуже в одну сторону: `**a\nb**` буквален для нас, но в
   * CommonMark это жирное — площадка выделяла ровно то, что страница
   * показывала звёздочками.
   */
  test('markdown снимает непарный маркер и пару через строку', () => {
    expect(editorHtml('Осталась **одна звёздочка в тексте.', 'markdown')).toBe(
      'Осталась одна звёздочка в тексте.'
    );
    expect(editorHtml('Начало **здесь\nи конец** там.', 'markdown')).toBe(
      'Начало здесь\nи конец там.'
    );
    // Пара внутри строки остаётся рабочей разметкой площадки.
    expect(editorHtml('Итог: **27,5%** с июля.', 'markdown')).toBe(
      'Итог: **27,5%** с июля.'
    );
  });

  test('пустой текст остаётся пустым у каждого редактора', () => {
    for (const editor of ['none', 'normal', 'markdown', 'html']) {
      expect(editorHtml('   \n  ', editor)).toBe('');
    }
  });
});

describe('переводчики разметки годятся поодиночке', () => {
  test('boldToStrong работает по уже экранированной строке', () => {
    expect(boldToStrong('a &lt;b&gt; **жирное**')).toBe(
      'a &lt;b&gt; <strong>жирное</strong>'
    );
  });

  test('stripBoldMarkers снимает только маркеры', () => {
    expect(stripBoldMarkers('**жирное** и * звёздочка')).toBe(
      'жирное и * звёздочка'
    );
  });
});

/**
 * Одна грамматика на страницу и на пост (разбор корректности, P2-13).
 *
 * Предпросмотр заготовки обещает «это уйдёт в канал». Пока выражений было
 * два, обещание не держалось, и меры сняты на живых строках: `**a **b** c**`
 * страница выделяла по краям, а пост по середине; `2 ** 3 = 8` пост молча
 * терял, оставляя двойной пробел; `***bold***` уходил в канал с одинокой `*`.
 *
 * Поэтому таблица ниже спрашивает ОБЕ стороны об одном и том же тексте.
 */
describe('страница и пост читают одну и ту же разметку', () => {
  const page = loadTypeScriptModule(
    'apps/frontend/src/components/content-intelligence/pieces/adaptation-markup.tsx'
  );

  /** Что выделила страница: содержимое пар, по порядку. */
  const pageBold = (text) => {
    const nodes = page.formatStoredMarkup(text);
    return (Array.isArray(nodes) ? nodes : [nodes])
      .filter((node) => node && typeof node === 'object' && node.props)
      .map((node) => node.props.children);
  };

  /** Что выделил пост: содержимое `<strong>`, по порядку. */
  const postBold = (text) =>
    [...editorHtml(text, 'html').matchAll(/<strong>(.*?)<\/strong>/gu)].map(
      (match) => match[1]
    );

  test.each([
    ['**a **b** c**', ['b']],
    ['**жирное**', ['жирное']],
    ['***bold***', ['bold']],
    ['2 ** 3 = 8', []],
    ['****', []],
    ['**a * b**', []],
    ['Одна ** и всё', []],
  ])('%s: обе стороны выделяют одно и то же', (text, bold) => {
    expect(pageBold(text)).toEqual(bold);
    expect(postBold(text)).toEqual(bold);
  });

  /**
   * Одинокий `**` между пробелами — это текст, а не маркер: возведение в
   * степень и сноска пишутся так же, как разметка. Ни одна сторона его не
   * трогает, и знаки не пропадают.
   */
  test.each(['2 ** 3 = 8', 'Сноска ** внизу', '****', 'Цена 5*5 и *акцент*'])(
    '%s остаётся собой и на странице, и в посте',
    (text) => {
      expect(page.formatStoredMarkup(text)).toBe(text);
      expect(editorHtml(text, 'html')).toBe(`<p>${text}</p>`);
      expect(editorHtml(text, 'markdown')).toBe(text);
      expect(editorHtml(text, 'none')).toBe(text);
    }
  );

  test('переключатель предлагается ровно там, где есть закрытая пара', () => {
    expect(page.hasStoredMarkup('2 ** 3 = 8')).toBe(false);
    expect(page.hasStoredMarkup('Одна ** и всё')).toBe(false);
    expect(page.hasStoredMarkup('****')).toBe(false);
    expect(page.hasStoredMarkup('**жирное**')).toBe(true);
    // Вопрос со своей памятью отвечал бы через раз: выражение собирается заново.
    expect(page.hasStoredMarkup('**жирное**')).toBe(true);
  });
});
