'use strict';
const fs=require('node:fs');
const {chromium}=require('playwright-core');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 globalThis.recoveryBrowser=browser;
 const context=await browser.newContext({viewport:{width:390,height:900},locale:'ru-RU',colorScheme:'dark',reducedMotion:'reduce'});
 await context.addCookies([{name:'i18next',value:'ru',url:'http://localhost:4219'}]);
 const page=await context.newPage();globalThis.recoveryPage=page;const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://localhost:4219/interface-review/agents?locale=ru&theme=dark&viewport=390&state=default',{waitUntil:'networkidle',timeout:120000});
 await page.getByRole('button',{name:'Чаты',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Чаты',exact:true});
 await dialog.getByRole('button',{name:/Ещё чаты/}).click();
 await dialog.getByRole('link',{name:/Синтетический чат 105 /}).click();
 await page.getByRole('button',{name:'Новый чат',exact:true}).click();
 await page.getByRole('button',{name:'First send fails',exact:true}).click();
 const text='Сохранить набранное при отказе до запуска';
 await page.getByRole('textbox').fill(text);await page.getByRole('textbox').press('Enter');
 await page.waitForFunction((expected)=>{const field=document.querySelector('textarea');return field?.value===expected && !field.closest('fieldset')?.disabled && window.__chatReview.calls.filter(c=>c.url==='/agent/chat').length===1;},text,{timeout:15000});
 const draft=await page.getByRole('textbox').inputValue();
 if(draft!==text)throw new Error('Pre-start failure lost the draft');
 const first=await page.evaluate(()=>window.__chatReview.calls.filter(c=>c.url==='/agent/chat').length);
 if(first!==1)throw new Error('Unexpected automatic retry after pre-start refusal: '+first);
 await page.getByRole('textbox').press('Enter');
 await page.getByText(/Synthetic delayed response for review-new-/).waitFor({timeout:15000});
 const second=await page.evaluate(()=>window.__chatReview.calls.filter(c=>c.url==='/agent/chat').length);
 if(second!==2)throw new Error('Explicit retry did not remain one send');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.screenshot({path:__dirname+'/390-dark-recovery.png',fullPage:true});
 console.log(JSON.stringify({threadsBeyondFirst100:true,preStartDraftRetained:true,noAutomaticRetry:first===1,explicitRetrySends:second,errors,horizontalOverflow:overflow,modelCalls:0},null,2));
 await context.close();await browser.close();
})().catch(async e=>{console.error(e);if(globalThis.recoveryPage){console.error(JSON.stringify(await globalThis.recoveryPage.evaluate(()=>({text:document.querySelector('textarea')?.value,api:window.__chatReview}))));}await globalThis.recoveryBrowser?.close();process.exitCode=1});
