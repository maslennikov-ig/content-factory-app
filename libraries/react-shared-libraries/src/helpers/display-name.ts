/**
 * Как продукт называет человека.
 *
 * Одна функция на все экраны. До 04.09.2026 их было три, каждая своя: список
 * команды писал `capitalize(email.split('@')[0]).split('.')[0]`, комментарии —
 * тот же приём без разреза по точке, а левый нижний угол рельса вообще
 * показывал адрес. Владелец ввёл имя в профиле и не увидел его ни в одном из
 * трёх мест: колонка `User.name` существовала, её просто никто не спрашивал.
 *
 * Порядок один и тот же везде: введённое имя, и только если его нет —
 * подстановка из адреса. Подстановка оставлена ровно такой, какой была в
 * списке команды, чтобы у людей, не заполнивших профиль, подпись не поменялась
 * заодно с исправлением: «maslennikov.ig@…» так и остаётся «Maslennikov».
 *
 * Функция чистая и без React — её берут и серверные компоненты, и клиентские.
 * Правило, по которому она обязана быть одна, держит `tests/display-name.test.cjs`.
 */

export interface DisplayNameSource {
  /** Имя из профиля. Пусто у всех, кто его не вводил. */
  name?: string | null;
  /** Адрес входа. Запасной источник подписи и ничего больше. */
  email?: string | null;
}

/** Подстановка из адреса: местная часть до первой точки, с заглавной буквы. */
const fromEmail = (email: string): string => {
  const local = email.split('@')[0].split('.')[0];
  if (!local) return '';
  return local.charAt(0).toUpperCase() + local.slice(1);
};

/**
 * Подпись человека для интерфейса. Пустая строка означает «мы не знаем о нём
 * ничего»; вызывающий решает, что рисовать вместо неё, — выдуманного имени
 * здесь не появляется.
 */
export const displayName = (source?: DisplayNameSource | null): string => {
  const name = (source?.name ?? '').trim();
  if (name) return name;

  const email = (source?.email ?? '').trim();
  if (!email) return '';

  return fromEmail(email);
};

/**
 * Первая буква подписи — для заглушки аватара. Пусто остаётся пустым: круг без
 * буквы честнее, чем «U» вместо неизвестного человека.
 */
export const initialOf = (source?: DisplayNameSource | null): string => {
  const shown = displayName(source);
  return shown ? shown.charAt(0).toUpperCase() : '';
};
