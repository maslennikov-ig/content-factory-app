/**
 * Разэкранирование сущностей — один проход и ни одним больше.
 *
 * `content-factory-next-97dq.11`. Цепочка вида
 * `.replace(/&amp;/gi, '&').replace(/&lt;/gi, '<')` разэкранирует дважды: то,
 * что первый проход только что написал, второй читает как разметку. Текст
 * `&amp;lt;` — это человек, написавший буквами «&lt;», — после двух проходов
 * становится `<`, то есть началом тега, которого в тексте не было.
 *
 * Здесь замена делается одним проходом по одному выражению: движок продолжает
 * поиск ПОСЛЕ совпадения и написанное замену не перечитывает. `&amp;lt;`
 * становится `&lt;` и останавливается там, где и должен.
 *
 * Таблица отдаётся вызывающим, а не зашита сюда: набор сущностей — это решение
 * о конкретном получателе (что понимает Telegram, что печатает Discord, что
 * считает мера голоса), а «разэкранировать ровно один раз» — решение общее.
 * Поэтому общее живёт здесь, а частное остаётся рядом со своим получателем.
 */

/** Сущность: исходник выражения и то, чем она становится. */
export type HtmlEntityTable = ReadonlyArray<readonly [string, string]>;

/**
 * Собирает разэкранировщик по таблице.
 *
 * Выражение собирается один раз на таблицу, а не на вызов. Каждая
 * альтернатива берётся в свою именованную группу `e<номер строки>`, и замена
 * находится по имени заполненной группы, поэтому `&#0?39;` и другие записи с
 * необязательной частью работают наравне с буквальными.
 *
 * `content-factory-next-97dq.19` (рецензия второго выпуска, P2-5): замена
 * искалась по номеру группы, и запись со своей группой внутри — например
 * `&(apos|#39);` — сдвинула бы нумерацию всех следующих, и они молча
 * разэкранировались бы не в те знаки. Имя от чужих групп не сдвигается.
 */
export const createEntityDecoder = (
  table: HtmlEntityTable
): ((value: string) => string) => {
  const pattern = new RegExp(
    table.map(([source], index) => `(?<e${index}>${source})`).join('|'),
    'gi'
  );

  return (value: string): string =>
    (value || '').replace(pattern, (...args: unknown[]) => {
      const named = args[args.length - 1] as Record<string, string | undefined>;
      const index = table.findIndex((_, row) => named[`e${row}`] !== undefined);
      return index === -1 ? (args[0] as string) : table[index][1];
    });
};
