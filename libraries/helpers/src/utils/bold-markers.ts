/**
 * Что такое «жирное» в этом продукте — одной грамматикой на страницу и на пост.
 *
 * `content-factory-next-97dq.2`, находка разбора корректности P2-13. Знак
 * выделения в теле адаптации один — `**текст**`, — но разбирали его двое и
 * по-разному: страница заготовки своим выражением, сборка поста своим. Меры
 * расхождения были сняты на живых строках:
 *
 *  - `**a **b** c**` — страница выделяла «a» и «c», пост выделял «b»;
 *  - `2 ** 3 = 8` — страница показывала строку целиком, пост молча терял
 *    звёздочки и оставлял двойной пробел;
 *  - `***bold***` — пост публиковал одинокую `*`.
 *
 * Обещание предпросмотра «это уйдёт в канал» держится только тогда, когда обе
 * стороны читают текст одним выражением, поэтому оно живёт здесь, в общей
 * прослойке, и импортируется и бэкендом, и экраном.
 *
 * Три правила, и каждое стоило одной из мер выше:
 *
 *  1. **Пара — внутри одной строки, краями к словам.** Содержимое без
 *     звёздочек и без перевода строки, первый и последний знак — не пробел.
 *     Поэтому `**a **` парой не считается, а `**b**` считается, и обе стороны
 *     выделяют один и тот же отрезок.
 *  2. **Одинокие `**` между пробелами — это текст.** Возведение в степень и
 *     сноска пишутся так же, как разметка, и снимать их значило бы менять
 *     написанное человеком. Маркером считается только тот `**`, что прижат к
 *     слову: его писали как разметку.
 *  3. **`****` и `*` не трогаем вовсе.** Четыре звёздочки — это четыре
 *     звёздочки, а одиночная — не наш знак; ни одна сторона их не разбирает.
 *
 * Выражения отдаются заводами, а не литералами: у `RegExp` с флагом `g` есть
 * своя память (`lastIndex`), и общий экземпляр между двумя вызовами — это
 * второй ответ на один вопрос. Ретроспективный просмотр (`(?<=…)`) собирается
 * через `new RegExp` по той же причине, по которой он не стоит в литерале
 * модуля: движок, который его не знает, упал бы на разборе файла целиком, а не
 * на вызове одной функции, — а страница в этом модуле пользуется только парой.
 */

/** Знак выделения. Другого в теле адаптации не хранится. */
export const BOLD_MARKER = '**';

/**
 * Пара: `**`, непробельный край, содержимое без `*` и без перевода строки,
 * непробельный край, `**`.
 */
export const BOLD_PAIR_SOURCE =
  '\\*\\*([^\\s*\\n](?:[^*\\n]*[^\\s*\\n])?)\\*\\*';

/**
 * Маркер, который писали как разметку: `**`, прижатый к слову хотя бы одной
 * стороной и не входящий в цепочку звёздочек.
 */
export const STRAY_BOLD_MARKER_SOURCE =
  '(?<=[^\\s*])\\*\\*(?![*])|(?<![*])\\*\\*(?=[^\\s*])';

/** Новый экземпляр на каждый разбор: `lastIndex` общего жил бы между вызовами. */
export const boldPairs = (): RegExp => new RegExp(BOLD_PAIR_SOURCE, 'gu');

/** Есть ли в тексте хотя бы одна закрытая пара. */
export const hasBoldPair = (text: string): boolean =>
  new RegExp(BOLD_PAIR_SOURCE, 'u').test(text || '');

/**
 * Пара или одинокий маркер — одним проходом.
 *
 * Порядок ветвей — это и есть правило: там, где начинается пара, она и
 * побеждает, поэтому маркеры пары никогда не попадают под ветвь одинокого.
 * Один проход вместо двух ещё и убирает ловушку: после снятия маркеров из
 * соседних строк могла бы сложиться новая «пара», которой в тексте не было.
 */
export const boldPairsOrStrayMarkers = (): RegExp =>
  new RegExp(`${BOLD_PAIR_SOURCE}|${STRAY_BOLD_MARKER_SOURCE}`, 'gu');

/**
 * Текст без нашей разметки: пары и одинокие маркеры сняты, звёздочки прозы
 * остались. Для редакторов, которые выделения не показывают.
 */
export const stripBoldMarkers = (text: string): string =>
  (text || '').replace(boldPairsOrStrayMarkers(), (_match, inner?: string) =>
    inner === undefined ? '' : inner
  );

/**
 * Текст, где пары остались собой, а одинокие маркеры сняты.
 *
 * Для площадок, чей редактор понимает `**текст**` сам (`markdown`): там пара —
 * рабочая разметка, а одинокий маркер — та самая звёздочка в вышедшем посте,
 * ради которой всё это написано.
 */
export const stripStrayBoldMarkers = (text: string): string =>
  (text || '').replace(boldPairsOrStrayMarkers(), (match, inner?: string) =>
    inner === undefined ? '' : match
  );
