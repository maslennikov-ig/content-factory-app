import { observePost } from './post-habits';
import { splitSentences } from './segment';
import type { LocalePack } from './locale-pack';

/**
 * Чего черновику не хватает, чтобы быть похожим, — и что с этим может сделать
 * только человек.
 *
 * ## Зачем
 *
 * Самая характерная привычка автора по замеру — он приносит собственные
 * измеренные числа: «прогнал шесть релизов через свой стенд», «дважды 89
 * баллов». У владельца это 54% постов. Модель, которой дали тему и не дали ни
 * одного факта, повторить этого не может: приносить ей нечего, и она пишет
 * общими словами. Манера скопирована, вещества нет, и человек видит текст,
 * который «вроде похож, но пустой».
 *
 * Замер 28.08.2026 показывает это в упор. В настоящих постах автора стоят
 * «$4078 или $9.30 в месяц», «медиана 3.68 секунды», «32 тысячи токенов» и
 * ссылка; в машинных — гладкий чек-лист без единого своего числа. И модель
 * права, что их не выдумывает.
 *
 * ## Что здесь решено, а что решено НЕ здесь
 *
 * Три варианта — молчать, предупреждать до генерации, отказываться писать без
 * фактов — владельцем отклонены все три (`pl1.10`). Принято четвёртое, и
 * уточнено им же 28.08.2026: продукт **предлагает**, а не спрашивает вместо
 * текста.
 *
 * 1. Пост выдаётся готовым и целым. Не заготовка с дыркой, не «вставьте сюда
 *    число» — текст, который можно отправить как есть, не отвечая ничего.
 *    Поэтому здесь нет ни одной функции, меняющей черновик: файл возвращает
 *    наблюдение и ничего больше.
 * 2. Рядом — предложение и **пример**. Пример берётся из собственного поста
 *    автора, а не сочиняется: он показывает форму, а не выдаёт факт. Своих
 *    цифр продукт не знает и знать не может.
 * 3. Отказ — обычный исход. Человек может захотеть и без цифры, и это не
 *    ошибка, не предупреждение и не повод что-либо переписывать.
 *
 * ## Почему предложение не появляется каждый раз
 *
 * «Придумывать вопросы для полноты» превращает генерацию в анкету — это
 * граница, записанная в самой задаче. Поэтому спрашивается только то, что
 * измеримо не хватает, и все четыре условия ниже проверяются числами, а не
 * ощущением.
 */

/** Двигается, когда меняется арифметика ниже. */
export const DRAFT_GAP_VERSION = 'draft-gaps/1.0.0';

/**
 * Доля постов автора, ниже которой привычка не считается его привычкой.
 *
 * Половина, и это не круглое число ради круглого. Ниже половины «он приносит
 * свои числа» — утверждение не об авторе, а о некоторых его постах, и
 * предложение, построенное на нём, будет срабатывать чаще, чем оправдываться.
 * У владельца привычка стоит на 54%, то есть порог отделяет её от шума с
 * запасом в четыре пункта — небольшим, и это честно назвать: следующий автор
 * с сорока девятью процентами предложения не получит, хотя почти такой же.
 *
 * Один порог на все привычки, если их станет больше. Порог, подобранный под
 * каждую, — это вкус с десятичной точкой, и эпик уже записал это правило для
 * полос отклонения.
 */
export const HABITUAL_SHARE = 50;

/** Меньше этого числа постов — доля случайна, и привычки нет. */
export const MIN_HABIT_POSTS = 20;

export type AuthorHabit = {
  /** Доля постов автора с этой привычкой, целыми процентами. */
  share: number;
  /** На скольких постах она посчитана. Знаменатель обязателен. */
  of: number;
};

export type DraftGap = {
  version: string;
  /** Что именно не хватает. Пока одна привычка; список растёт замером. */
  metric: 'carriesOwnMeasurement';
  /** Насколько это привычка автора — числа, которые человек может проверить. */
  authorShare: number;
  authorOf: number;
  /**
   * Предложение формы на примере собственного поста автора. `null`, когда
   * подходящего примера не нашлось: выдумать его нельзя, а предложение без
   * примера всё ещё осмысленно.
   */
  example: string | null;
};

/**
 * Предложение формы — предложение из собственного поста автора.
 *
 * Берётся самое короткое подходящее: пример читается мельком, рядом с готовым
 * текстом, и абзац на пять строк в этой роли не пример, а второй пост.
 * Годится только предложение, которое само несёт число рядом с единицей, —
 * иначе оно ничего не показывает.
 */
export function measurementExample(
  texts: readonly string[],
  pack: LocalePack
): string | null {
  let best: string | null = null;
  for (const text of texts) {
    for (const sentence of splitSentences(String(text ?? ''), pack)) {
      const body = sentence.text.trim();
      if (!body || body.length > 200) continue;
      if (!observePost(body, pack).carriesOwnMeasurement) continue;
      if (best === null || body.length < best.length) best = body;
    }
  }
  return best;
}

/**
 * @param text черновик целиком, как его получит человек
 * @param habit привычка автора, измеренная на его корпусе
 * @param examples собственные посты автора — источник примера и ничего больше
 * @param hasMaterial дал ли человек факты к этой теме
 * @returns `null`, когда предлагать нечего. Это обычный исход, а не отсутствие
 *   ответа: молчание здесь — половина решения владельца.
 */
export function draftGap(
  text: string,
  habit: AuthorHabit | null | undefined,
  examples: readonly string[],
  hasMaterial: boolean,
  pack: LocalePack
): DraftGap | null {
  const body = String(text ?? '').trim();
  if (!body) return null;

  /**
   * Человек уже дал факты — вопрос задан и отвечен.
   *
   * Если материал приложен, а число в черновик всё равно не попало, это другой
   * дефект: модель не воспользовалась тем, что ей дали. Просить у человека
   * второй раз то, что он уже принёс, — ровно та анкета, которую задача
   * запрещает.
   */
  if (hasMaterial) return null;

  if (!habit || habit.of < MIN_HABIT_POSTS) return null;
  if (habit.share < HABITUAL_SHARE) return null;

  /**
   * В черновике число уже есть — предлагать нечего.
   *
   * Тем же предикатом, которым привычка считалась на корпусе. Второй
   * реализации «есть ли здесь собственное измерение» не заводится: две
   * функции разошлись бы молча, обе возвращают булево.
   */
  if (observePost(body, pack).carriesOwnMeasurement !== false) return null;

  return {
    version: DRAFT_GAP_VERSION,
    metric: 'carriesOwnMeasurement',
    authorShare: habit.share,
    authorOf: habit.of,
    example: measurementExample(examples, pack),
  };
}
