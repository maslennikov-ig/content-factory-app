import {
  countNgrams,
  type CharacterNgramProfile,
} from './character-ngrams';
import {
  fingerprintOf,
  type AlignedImpostor,
  type ImpostorSet,
} from './impostors';
import type { BrandVoiceLocale } from './brand-voice.types';

/**
 * Шеренга для опознания, собранная под конкретного автора.
 *
 * ## Что было не так с прежней
 *
 * До 27.08.2026 подставными были три файла документации этого репозитория,
 * одни и те же для всех. Подозреваемый пишет посты в Telegram, а в шеренге
 * стоят руководства по развёртыванию: у них выигрывает почти любой текст,
 * похожий на пост, включая генерацию вообще без голоса.
 *
 * Замер на трёх настоящих русских каналах, потолок (отложенные посты автора)
 * против пола (генерация без голоса):
 *
 * | автор | документация | другие авторы |
 * | --- | --- | --- |
 * | 153 поста | 86,4 / 29,2 = запас 57,2 | 44,6 / 0,0 = запас 44,6 |
 * | 1023 поста | 91,1 / 72,7 = запас 18,4 | 51,9 / 4,4 = запас 47,5 |
 * | 125 постов | 96,1 / 80,0 = запас 16,1 | 64,5 / 16,7 = запас 47,9 |
 *
 * Запас, разъезжавшийся втрое, сошёлся в три пункта. Оба ресерча 27.08.2026
 * отвечают на вопрос о нормировке одинаково: опубликованной автор-независимой
 * нормировки выхода General Impostors нет, зато вся линия работ — Koppel &
 * Winter 2014, Potha & Stamatatos 2017 — говорит одно: подставных подбирают
 * под задачу. «В опознании не набирают подозреваемых с улицы».
 *
 * ## Почему она теперь свойство разбора, а не файла
 *
 * Шеренга собирается из настоящих коротких текстов других авторов системы —
 * того же жанра по построению, а не по совпадению. В сборке её держать нельзя:
 * это чужие тексты конкретных людей, и любой из них завтра может оказаться
 * автором, для которого эта шеренга строится. Тогда он сравнивался бы с собой,
 * выиграть у себя не смог бы, и голосование поехало бы вниз без единого
 * признака неисправности.
 *
 * ## Почему это дёшево
 *
 * Голосование спрашивает подставного только про окна из отпечатка автора и ни
 * про какие другие. Поэтому здесь хранится не словарь на пять тысяч ключей, а
 * ровно столько чисел, сколько окон в отпечатке, в том же порядке. Шеренга
 * весит примерно столько же, сколько сам отпечаток, и лежит рядом с ним.
 *
 * ## Сколько подставных
 *
 * Замер того же дня: 6, 12 и 20 подставных, нарезанных из двух чужих корпусов,
 * дали монотонно убывающее качество — 0.826, 0.823, 0.819 среднего AUC. Больше
 * кусков одних и тех же людей не помогает. «Сто подставных» у Ranking-Based
 * Impostors — это сто разных авторов, и рост здесь покупается людьми, а не
 * нарезкой.
 */

/** Двигается, когда меняется арифметика ниже. */
export const LINEUP_VERSION = 'lineup/1.0.0';

/**
 * На сколько подставных режется чужой материал.
 *
 * Шесть: столько получилось из двух чужих корпусов по три части в замере, на
 * котором снята таблица выше, и добавление кусков сверх этого только вредило.
 */
export const LINEUP_SIZE = 6;

/** Меньше этого числа чужих текстов — шеренги нет, а не маленькая шеренга. */
export const MIN_LINEUP_TEXTS = 12;

/**
 * Каждый шестой чужой текст не попадает в шеренгу и служит отрицательным
 * примером для порога.
 *
 * ## Почему их нельзя брать одни и те же
 *
 * Порог выбирается по тому, сколько голосов набирает чужой текст. Если этот
 * текст участвовал в постройке подставного, он проигрывает своему же
 * подставному и набирает почти ноль — а порог, снятый на таких, оказывается
 * лежащим на полу. Ошибка бесшумная: числа выглядят прекрасно, чужие проходят
 * в трёх процентах случаев, и только генерации внезапно проходят тоже.
 *
 * Замер 27.08.2026, доля генераций, принятых за автора:
 *
 * | автор | материал общий | материал раздельный |
 * | --- | --- | --- |
 * | owner | 23% | **2%** |
 * | avetov | 30% | **23%** |
 * | britva | 55% | **45%** |
 *
 * Свои посты при этом по-прежнему получают «похоже» в 89%, 78% и 76% случаев.
 *
 * ## Почему каждый шестой, а не последняя шестая часть
 *
 * Тексты лежат по времени. Отрезанный хвост — это то, как несколько человек
 * писали позже всего, и порог оказался бы снят на одном периоде их жизни.
 */
export const NEGATIVE_EVERY = 6;

/**
 * Чужой материал, разложенный по двум ролям.
 *
 * Одна функция, а не два вызова с договорённостью: разложение обязано быть
 * одинаковым у продукта и у стенда, иначе стенд меряет не то, чем судит
 * продукт, — а ради этого совпадения стенд и существует.
 */
export function splitForeign(texts: readonly string[]): {
  lineup: string[];
  negatives: string[];
} {
  const lineup: string[] = [];
  const negatives: string[] = [];
  texts.forEach((text, index) => {
    if (index % NEGATIVE_EVERY === 0) negatives.push(text);
    else lineup.push(text);
  });
  return { lineup, negatives };
}

/**
 * @param foreign настоящие тексты авторов, которыми этот автор не является
 * @param print отпечаток, по окнам которого выравниваются веса
 * @returns `null`, когда чужого материала не набралось; вызывающий тогда
 *   говорит «шеренги нет» вместо того, чтобы судить по двум подставным
 */
export function buildLineup(
  foreign: readonly string[],
  print: CharacterNgramProfile | null | undefined,
  locale: BrandVoiceLocale,
  parts: number = LINEUP_SIZE
): ImpostorSet | null {
  if (!print?.grams?.length) return null;
  if (foreign.length < MIN_LINEUP_TEXTS) return null;

  const perPart = Math.floor(foreign.length / parts);
  if (perPart < 1) return null;

  /**
   * Окна автора множеством, а не списком.
   *
   * Проверка «нужно ли это окно» делается один раз на каждое окно каждого
   * чужого текста — это сотни тысяч обращений на разбор, и поиск по массиву из
   * тысячи строк превратил бы сборку шеренги в самое дорогое место разбора.
   */
  const wanted = new Set(print.grams);

  const impostors: AlignedImpostor[] = [];
  for (let index = 0; index < parts; index += 1) {
    const slice =
      index === parts - 1
        ? foreign.slice(index * perPart)
        : foreign.slice(index * perPart, (index + 1) * perPart);

    const pooled = new Map<string, number>();
    let total = 0;
    for (const text of slice) {
      for (const [gram, count] of countNgrams(text, print.size)) {
        /**
         * Считается всё, а сохраняются только окна автора.
         *
         * Знаменатель обязан быть по всему, что подставной написал, иначе его
         * частоты нормированы на чужой словарь и любое расстояние до него
         * оказывается не тем, что сравнивается с расстоянием до автора.
         */
        total += count;
        if (wanted.has(gram)) {
          pooled.set(gram, (pooled.get(gram) ?? 0) + count);
        }
      }
    }
    if (!total) continue;
    impostors.push(
      print.grams.map(
        (gram) => Math.round(((pooled.get(gram) ?? 0) / total) * 1e6) / 1e6
      )
    );
  }
  if (!impostors.length) return null;

  return {
    version: `${LINEUP_VERSION}/${impostors.length}`,
    locale,
    source: 'настоящие короткие тексты других авторов системы',
    size: print.size,
    impostors,
    alignedTo: fingerprintOf(print),
  };
}
