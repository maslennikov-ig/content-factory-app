/**
 * Рабочая точка голосования, снятая для одного автора.
 *
 * ## Почему одного порога на всех не бывает
 *
 * До 27.08.2026 порогом была константа `IMPOSTOR_VOTE_FLOOR = 2/3`, снятая на
 * одном авторе в одном языке. Замер на трёх корпусах показал, что она не
 * переносится: на новой шеренге она отвергала 71%, 58% и 41% собственных
 * отложенных постов автора — то есть чаще всего сообщала человеку, что его
 * собственный текст написан не им.
 *
 * Один порог не живёт и после починки шеренги. При 33% голосов у одного автора
 * чужих проходит 0%, у другого — 45%. Оба ресерча 27.08.2026 отвечают на это
 * одинаково: в опубликованной литературе автор-независимой нормировки выхода
 * General Impostors нет, а рабочая точка выбирается на размеченном материале —
 * положительном и отрицательном сразу. Halvani, Winter & Graner (DFRWS EU 2016)
 * учат отдельный порог на каждый язык; Nini et al. (13.03.2024) прямо разделяют
 * unary-методы, знающие только разброс автора, и методы, вводящие
 * конкурирующую популяцию.
 *
 * ## Почему одного разброса автора мало
 *
 * Соблазн был: взять 95-й перцентиль собственных расстояний автора и объявить
 * правилом. Замер 27.08.2026: пятый перцентиль голосов автора на его же
 * отложенных постах равен **нулю** на всех трёх корпусах — часть настоящих
 * текстов человека не выигрывает ни одного сравнения из шестидесяти. Правило,
 * построенное на одном этом распределении, пропускает сто процентов генераций,
 * ровно как абсолютный порог, который эпик уже похоронил. Односторонняя мерка
 * не измеряет ложных пропусков, сколько бы положительных примеров ей ни дали.
 *
 * ## Два порога, а между ними «не знаю»
 *
 * Верхний порог отвечает за утверждение «похоже на автора», и ошибка в нём —
 * назвать авторским чужой текст. Нижний отвечает за «не похоже», и ошибка в
 * нём — отвергнуть настоящий текст человека. Ошибки разной цены, поэтому у них
 * разные пороги, а промежуток между ними не достаётся ни одному из двух ответов
 * и называется вслух.
 *
 * Замер 27.08.2026, оба допуска по 5%:
 *
 * | автор | «не похоже» | «не знаю» | «похоже» | чужих принято |
 * | --- | --- | --- | --- | --- |
 * | owner | 8% | 34% | 58% | 3% |
 * | avetov | 6% | 26% | 67% | 3% |
 * | britva | 7% | 31% | 62% | 3% |
 *
 * Треть собственных текстов автора остаётся без ответа, и это не изъян, а
 * длина: один пост на шестьсот-восемьсот знаков несёт столько признаков,
 * сколько несёт, и молчание честнее уверенного ответа монеткой.
 *
 * ## Чем отрицательные примеры быть могут и чем не могут
 *
 * Чужие настоящие авторы — бесплатны и уже есть в системе. Ими и снимался
 * порог до 28.08.2026. Но замер 27.08 показал границу этого материала: порог,
 * выбранный так, чтобы пропускать 3% чужих людей, пропускает 0%, 16% и 30%
 * генераций — текст, написанный моделью под голос человека, прячется лучше,
 * чем другой человек.
 *
 * ## Два противника — два обещания, и точка берётся строже
 *
 * Замер 28.08.2026 на трёх корпусах, шестнадцать тем, обрезка 800. Слева —
 * порог, снятый только на чужих людях; справа — только на сохранённых
 * генерациях того же прогона. Доля генераций, принятых за авторские:
 *
 * | автор | по чужим людям | по генерациям |
 * | --- | --- | --- |
 * | owner | 2,7% | 3,6% |
 * | avetov | 9,8% | 2,7% |
 * | britva | **33,0%** | **8,0%** |
 *
 * Ни одна из двух точек не годится за обе: порог по людям пускает треть
 * генераций у одного автора, порог по генерациям пускает вдвое больше людей у
 * другого (6,1% против 3,0% у owner). Поэтому обещание не одно, а два — по
 * пять процентов на каждую популяцию, — и точка берётся та, что держит оба:
 * бо́льшая из двух. Подбираемого веса между ними нет и быть не может:
 * шестнадцать генераций на корпус — выборка, на которой любой вес был бы
 * подогнан под неё же.
 *
 * Цена этого правила велика, и владелец за неё заплатил допуском, а не
 * отказом от правила: строгость снижена с пяти процентов до пятнадцати
 * (28.08.2026, см. `MAX_FALSE_ACCEPT`). Доля собственных постов автора,
 * получающих «похоже»:
 *
 * | автор | по чужим людям, 5% | по обеим, 5% | **отгружено: по обеим, 15%** |
 * | --- | --- | --- | --- |
 * | owner | 84,2% | 84,2% | **94,7%** |
 * | avetov | 58,8% | 35,3% | **70,6%** |
 * | britva | 75,9% | 37,9% | **48,3%** |
 *
 * То, что не попало ни в «похоже», ни в «не похоже», уходит в молчание. Мерка,
 * целящаяся в настоящего противника, чаще отказывается отвечать, и на самом
 * маленьком корпусе она молчит даже на пятнадцати процентах — там дело не в
 * допуске, а в разделимости (58,0% против отгружаемого блока).
 *
 * ## Почему это ничего не ломает у тех, кому нечем мериться
 *
 * Генерации берутся из `BrandVoiceEdit` — пар «что предложил продукт, что
 * отправил человек», — и только те, которые человек действительно переписал:
 * черновик, отправленный как есть, автор признал своим, и отрицательным
 * примером он не является. Пока таких пар меньше `MIN_CALIBRATION_SAMPLES`,
 * вторая сторона просто отсутствует и порог остаётся прежним. У трёх боевых
 * голосов на 28.08.2026 их нет ни одной, поэтому выкат этой правки не двигает
 * ни один вердикт, пока пространство само не напишет достаточно.
 *
 * Через границу арендатора при этом ходят числа. Чужие тексты читает серверная
 * задача, наружу отдаётся распределение баллов, и ни одного чужого предложения
 * никуда не переносится. Генерации границы вовсе не пересекают — они
 * собственные тексты того же пространства.
 */

/** Двигается, когда меняется арифметика ниже. */
export const CALIBRATION_VERSION = 'voice-calibration/1.2.0';

/**
 * Доля чужих текстов, которую верхнему порогу позволено принять за авторские.
 *
 * Не ноль: ноль на выборке в три десятка текстов означает «ни одного
 * наблюдения не попало», а не «ошибка невозможна», и порог, выбранный так,
 * уезжает в единицу от одного удачного чужого поста.
 *
 * ## Почему пятнадцать, а не пять
 *
 * Пять процентов — обычная точка для проверки такого рода, и до 28.08.2026
 * стояла она. Против настоящего противника она оказалась слишком дорогой:
 * молчание вместо ответа получала половина собственных постов автора. Решение
 * владельца 28.08.2026 — снизить строгость.
 *
 * Пятнадцать выбраны по замеру на трёх корпусах, а не по вкусу. Доля
 * собственных постов автора, получающих «похоже», и рядом — доля чужих ЛЮДЕЙ,
 * которых порог принял за авторские:
 *
 * | допуск | owner | avetov | britva | чужих людей принято |
 * | --- | --- | --- | --- | --- |
 * | 5% | 84,2% | 35,3% | 37,9% | до 3,0% |
 * | 10% | 94,7% | 58,8% | 37,9% | до 9,1% |
 * | **15%** | **94,7%** | **72,5%** | **51,7%** | **до 9,1%** |
 * | 20% | 94,7% | 76,5% | 51,7% | **до 16,7%** |
 *
 * Пятнадцать — колено этой кривой. Дальше растёт не польза, а ложная похвала
 * чужому тексту: на двадцати процентах проверка говорит «похоже на вас» тексту
 * другого человека в каждом шестом случае, и это та ошибка, которую продукт
 * обещает вслух. Машинный текст на пятнадцати по-прежнему останавливается в
 * шести-семи случаях из семи (пропущено 7,2%, 14,9% и 14,4%).
 *
 * Строка «15%» пересчитана 28.08.2026 на утроенном материале — 208 генераций на
 * корпус вместо 112, после того как трек отбора черновиков оплатил ещё два
 * прогона. Числа сдвинулись на единицы процентов и выбор допуска не изменили;
 * остальные строки остались на прежней выборке и потому помечены здесь.
 *
 * Допуск один на обе популяции намеренно. Два числа — чужим людям одно, своим
 * генерациям другое — это два обещания, которые расходятся молча, а разницу
 * между ними никто не измерял.
 */
export const MAX_FALSE_ACCEPT = 0.15;

/** Доля собственных текстов автора, которую нижнему порогу позволено отвергнуть. */
export const MAX_FALSE_REJECT = 0.05;

/**
 * Меньше двадцати наблюдений с любой стороны — калибровки нет.
 *
 * Пятипроцентный допуск на выборке в двадцать текстов это одно наблюдение.
 * Ниже этого порог перестаёт быть свойством автора и становится свойством
 * того, какой пост случайно попал в отложенную часть.
 */
export const MIN_CALIBRATION_SAMPLES = 20;

export type CalibrationErrors = {
  /** Сколько текстов проверено и на скольких из них ответ был неверным. */
  of: number;
  wrong: number;
};

export type VoiceCalibration = {
  version: string;
  /** Голосов, ниже или равно которым текст называется непохожим. */
  low: number | null;
  /** Голосов, выше или равно которым текст называется похожим. */
  high: number | null;
  /** Что «похоже» сделало с чужими текстами — доля ложно принятых. */
  falseAccept: CalibrationErrors | null;
  /** Что «не похоже» сделало с текстами автора — доля ложно отвергнутых. */
  falseReject: CalibrationErrors | null;
  /**
   * Из чего собраны отрицательные примеры. `foreign_avatars` — настоящие
   * тексты других авторов системы; `own_generations` — то, что продукт написал
   * этому пространству сам.
   */
  negatives: 'foreign_avatars' | 'own_generations' | 'mixed' | null;
  /** Почему калибровки нет, когда её нет. */
  reason?: 'TOO_FEW_OWN' | 'TOO_FEW_FOREIGN';
};

export const UNCALIBRATED: VoiceCalibration = {
  version: CALIBRATION_VERSION,
  low: null,
  high: null,
  falseAccept: null,
  falseReject: null,
  negatives: null,
};

/**
 * Снята ли мерка — одним ответом, в одном месте.
 *
 * Обе границы или ни одной: точка с одной границей не бывает, а проверка
 * «есть объект калибровки» пропустила бы `UNCALIBRATED`, который объект и
 * есть. Раньше это условие стояло только внутри `verdictFor`; теперь его
 * читает и паспорт, а расписанное дважды оно рано или поздно разойдётся —
 * и разойдётся бесшумно, потому что оба ответа булевы.
 */
export function isCalibrated(
  calibration: VoiceCalibration | null | undefined
): boolean {
  return !!calibration && calibration.high !== null && calibration.low !== null;
}

/**
 * Наименьшая точка, выше или равно которой лежит не больше `share` списка.
 *
 * Точки берутся из самих наблюдений, а не из сетки: сетка с шагом 0.01 на
 * голосовании из шестидесяти раундов предлагает пороги, которых голосование
 * никогда не выдаёт, и выбор между ними — выбор между одинаковыми ответами.
 */
const smallestAbove = (
  points: readonly number[],
  negatives: readonly number[],
  share: number
): number => {
  for (const point of points) {
    const accepted =
      negatives.filter((one) => one >= point).length / negatives.length;
    if (accepted <= share) return point;
  }
  return 1;
};

/** Наибольшая точка, ниже или равно которой лежит не больше `share` списка. */
const largestBelow = (
  points: readonly number[],
  positives: readonly number[],
  share: number
): number => {
  for (let index = points.length - 1; index >= 0; index -= 1) {
    const point = points[index];
    const rejected =
      positives.filter((one) => one <= point).length / positives.length;
    if (rejected <= share) return point;
  }
  return 0;
};

/**
 * Чем эти отрицательные примеры были — по тому, что действительно участвовало.
 *
 * Раньше это был параметр, и параметр мог соврать: вызывающий передавал
 * `foreign_avatars`, а в списке лежала смесь. Теперь поле выводится из того,
 * какие популяции набрали материал, и разойтись с ним не может.
 */
const sourceOf = (
  foreign: number,
  generated: number
): VoiceCalibration['negatives'] => {
  if (foreign && generated) return 'mixed';
  if (generated) return 'own_generations';
  return 'foreign_avatars';
};

/**
 * @param own голоса, набранные отложенными текстами самого автора — теми, что
 *   отпечаток не строили. Тексты из обучающей части сюда не годятся: они
 *   набирают больше, чем набрал бы следующий пост, и порог поедет вверх.
 * @param foreign голоса, набранные настоящими текстами других авторов системы
 * @param generated голоса, набранные тем, что продукт написал этому
 *   пространству сам и человек переписал. Пусто — обещание одно, и правило
 *   ровно то же, что было до 28.08.2026.
 */
export function calibrate(
  own: readonly number[],
  foreign: readonly number[],
  generated: readonly number[] = []
): VoiceCalibration {
  if (own.length < MIN_CALIBRATION_SAMPLES) {
    return { ...UNCALIBRATED, reason: 'TOO_FEW_OWN' };
  }
  /**
   * Популяция, которой не набралось на обещание, не участвует вовсе.
   *
   * Не «участвует хуже»: пятипроцентный допуск на пятнадцати наблюдениях —
   * это ноль наблюдений, и точка, снятая по такой популяции, свойство не
   * автора, а того, какие пятнадцать текстов случайно нашлись.
   */
  const populations = [foreign, generated].filter(
    (one) => one.length >= MIN_CALIBRATION_SAMPLES
  );
  if (!populations.length) {
    return { ...UNCALIBRATED, reason: 'TOO_FEW_FOREIGN' };
  }

  /**
   * Сетка точек одна на все популяции.
   *
   * Две точки, выбранные на разных сетках, нельзя сравнивать между собой, а
   * ниже из них берётся бо́льшая. Ошибка была бы бесшумной: обе лежат в
   * нуле-единице и обе выглядят как доля голосов.
   */
  const against = populations.flat();
  const points = [...new Set([...own, ...against])].sort(
    (left, right) => left - right
  );
  /**
   * Строже из двух обещаний, а не среднее и не смесь.
   *
   * Чужие люди и собственные генерации — две разные популяции, и пять
   * процентов обещаны каждой. Точка, снятая на их объединении, держит
   * обещание только для суммы: она разбавляет ту сторону, которой меньше, и
   * именно ту, ради которой задача открыта. Максимум держит оба.
   */
  const high = Math.max(
    ...populations.map((one) => smallestAbove(points, one, MAX_FALSE_ACCEPT))
  );
  const low = largestBelow(points, own, MAX_FALSE_REJECT);

  /**
   * Нижний порог никогда не поднимается до верхнего.
   *
   * У автора с очень узким разбросом обе точки могут сойтись, и тогда полоса
   * «не знаю» схлопывается, а два ответа начинают спорить о границе. Тогда
   * «не похоже» остаётся только тексту, не выигравшему ни одного сравнения из
   * шестидесяти: сказать человеку, что его текст написан не им, дороже, чем
   * промолчать.
   *
   * Ноль здесь — не отсутствие границы, и путать это нельзя. Замер 28.08.2026
   * на трёх корпусах: «не похоже» при нуле голосов достаётся 75,0%, 51,8% и
   * 1,8% генераций и 81,8%, 66,7% и 58,1% чужих людей, ценой 5,3%, 5,9% и
   * 6,9% собственных постов автора. На двух корпусах из трёх это самая
   * работающая половина всей мерки, и убрать её значило бы отдать три четверти
   * пойманного машинного текста ради одного поста из двадцати.
   */
  const floor = low < high ? low : 0;

  return {
    version: CALIBRATION_VERSION,
    low: floor,
    high,
    falseAccept: {
      of: against.length,
      wrong: against.filter((one) => one >= high).length,
    },
    falseReject: {
      of: own.length,
      wrong: own.filter((one) => one <= floor).length,
    },
    negatives: sourceOf(
      foreign.length >= MIN_CALIBRATION_SAMPLES ? foreign.length : 0,
      generated.length >= MIN_CALIBRATION_SAMPLES ? generated.length : 0
    ),
  };
}

export type CalibratedVerdict = 'CLOSE' | 'FAR' | 'CANNOT_TELL';

/**
 * @returns `null` when there is no calibration to read the vote against — the
 *   caller says «не калибровано» rather than inventing a boundary.
 */
export function verdictFor(
  votes: number | null | undefined,
  calibration: VoiceCalibration | null | undefined
): CalibratedVerdict | null {
  if (votes === null || votes === undefined) return null;
  if (!isCalibrated(calibration)) return null;
  if (votes >= calibration!.high!) return 'CLOSE';
  if (votes <= calibration!.low!) return 'FAR';
  return 'CANNOT_TELL';
}
