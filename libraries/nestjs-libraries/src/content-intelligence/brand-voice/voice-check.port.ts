/**
 * Вердикт голоса для квитанции адаптации — портом, а не классом.
 *
 * `content-factory-next-k879.1`, решение владельца 07.09.2026. Заготовки и
 * вход одной мыслью спрашивают «похоже ли это на автора» тем же именем, что и
 * граф спрашивает мерку отбора (`DRAFT_VOICE_JUDGE`), и по той же причине:
 * тащить голосовой модуль в генерацию значило бы завести вторую сборку мерки,
 * а мерка в этом эпике одна.
 *
 * Порт даёт ровно один ответ — одно слово и причину молчания. Ни отпечатка,
 * ни шеренги, ни восьми шкал наружу не уходит: всё это относится к тем
 * границам, против которых посчитан голос, и собранное отдельно однажды
 * разъедется с вердиктом, который объясняет.
 */

import type { VoiceCheckReportV1 } from './voice-wiring.contract';

export const VOICE_CHECK_PORT = 'VOICE_CHECK_PORT';

export type VoiceCheckPort = {
  /**
   * Никогда не бросает. Проверка не должна быть причиной, по которой человек
   * не увидел свой текст, — то же правило, что у порогов проверки на штампы.
   */
  voiceCheckFor(
    organizationId: string,
    text: string,
    locale: 'ru' | 'en'
  ): Promise<VoiceCheckReportV1>;
  /**
   * Несколько текстов одной области — против ОДНОГО разбора.
   *
   * `content-factory-next-97dq.2`, разбор корректности P1-2: страница
   * заготовки спрашивает вердикт на каждую адаптацию, а `voiceCheckFor`
   * каждый раз заново читает разбор области и её мерку — четыре запроса на
   * строку, двадцать строк на страницу. Разбор у области один и за одно
   * чтение страницы не меняется, поэтому он читается один раз, а тексты
   * меряются против него по очереди.
   *
   * Необязателен: порт без него остаётся прежним портом, а зовущий считает по
   * одному. Так же не бросает, и отвечает ровно столько же ответов, сколько
   * пришло текстов.
   */
  voiceCheckMany?(
    organizationId: string,
    texts: readonly string[],
    locale: 'ru' | 'en'
  ): Promise<VoiceCheckReportV1[]>;
};

/**
 * Ответ, когда спрашивать не у кого: порт не подключён вовсе.
 *
 * `UNKNOWN` с причиной, а не `CLOSE`: молчание — это молчание, и экран,
 * рисующий его одобрением, сообщает человеку то, чего никто не проверял.
 */
export const VOICE_CHECK_SILENT: VoiceCheckReportV1 = {
  verdict: 'UNKNOWN',
  reason: 'NO_PROFILE',
};
