/**
 * Речь о тексте вместо текста (`content-factory-next-97dq.90`, пятнадцатый
 * заход, `cnt-36`).
 *
 * Суть — готовый пост от первого лица автора. Первая суть `cnt-36` вместо
 * этого рассказывала о материале и ответах: «сначала я описал это как
 * сокращение вдвое, а в ответе уточнил…», «конкретных деталей нет. Здесь
 * можно рассказать о результате». Промпт `core-write/v13` это запрещает; эта
 * проверка ловит то, что всё же проскочило, и суть переписывается один раз.
 *
 * Только цельные обороты о тексте, ответе и поправке (ревью W1 пятнадцатого
 * захода, F8). Одиночные «в материале», «в брифе», «в этом тексте»,
 * «деталей нет», «как я уже писал», «об этом стоит рассказать» пишет и
 * обычный автор — «в брифе клиента не было дедлайна», «писал об этом в
 * материале для РБК», «пока деталей нет», — и каждая такая фраза стоила
 * платной переписи, которая снимала слова автора.
 *
 * Чистая и детерминированная: ни модели, ни сети. Обе локали проверяются
 * всегда — вход бывает смешанным, а оборот на чужом языке в сути так же не к
 * месту. Границы слов — через `\p{L}`, потому что `\b` в JS кириллицу не
 * видит.
 */

const L = '\\p{L}\\p{Nd}';
const START = `(?<![${L}])`;
const END = `(?![${L}])`;

const phrase = (body: string): RegExp => new RegExp(`${START}(?:${body})${END}`, 'giu');

/** Обороты, которые в готовом тексте поста не стоят никогда. */
export const META_SPEECH_PATTERNS: readonly RegExp[] = [
  // RU: о прежнем тексте и о поправке.
  phrase('в\\s+перв(?:ом|ой)\\s+(?:описании|версии|варианте|тексте)'),
  phrase('сначала\\s+я\\s+(?:описал[а]?|написал[а]?|сказал[а]?)'),
  phrase('в\\s+(?:своём\\s+|своем\\s+)?ответе\\s+(?:я\\s+)?(?:уточнил[а]?|поправил[а]?|указал[а]?|написал[а]?|ответил[а]?)'),
  phrase('(?:уточнил[а]?|поправил[а]?)\\s+в\\s+ответе'),
  // RU: о том, что можно было бы написать.
  phrase('здесь\\s+(?:можно|стоит|следует|нужно)\\s+(?:рассказать|написать|описать|добавить)'),
  // RU: об отсутствии материала — только цельным оборотом.
  phrase('конкретных\\s+(?:деталей|подробностей|примеров|шагов)\\s+(?:в\\s+материале\\s+)?нет'),
  // RU: о входе и о решениях.
  phrase('в\\s+исходном\\s+материал(?:е|ах)'),
  phrase('решени(?:е|я|ю|ем)\\s+модели'),
  phrase('модель\\s+решила'),
  phrase('без\\s+конкретного\\s+эпизода'),
  phrase('этот\\s+текст\\s+объясняет'),
  // EN.
  phrase('in\\s+(?:the|my)\\s+first\\s+(?:description|version|draft)'),
  phrase('at\\s+first\\s+i\\s+(?:described|wrote|said)'),
  phrase('in\\s+(?:my|the)\\s+answer,?\\s+(?:i\\s+)?(?:clarified|corrected|specified|said|wrote)'),
  phrase('here\\s+(?:one|you|we|i)\\s+(?:could|can|might|should)\\s+(?:tell|write|describe|add)'),
  phrase('there\\s+are\\s+no\\s+(?:concrete|specific)\\s+(?:details|examples|steps)'),
  phrase('in\\s+the\\s+source\\s+material'),
  phrase("the\\s+model(?:'|’)s\\s+decision"),
  phrase('the\\s+model\\s+decided'),
  phrase('without\\s+a\\s+concrete\\s+episode'),
  phrase('this\\s+text\\s+explains'),
];

/**
 * Найденные обороты, каждый один раз, в том виде, в каком стоят в тексте.
 * Пусто — суть говорит сама за себя.
 */
export const metaSpeechIn = (text: string): string[] => {
  const found = new Map<string, string>();
  for (const pattern of META_SPEECH_PATTERNS) {
    pattern.lastIndex = 0;
    for (const match of text.matchAll(pattern)) {
      const hit = match[0].replace(/\s+/gu, ' ').trim();
      const key = hit.toLowerCase();
      if (!found.has(key)) found.set(key, hit);
    }
  }
  return [...found.values()];
};
