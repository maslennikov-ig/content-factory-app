/**
 * Форма правила проверки на штампы и границы слова, работающие с кириллицей.
 *
 * `content-factory-next-tu3k.3`. Файл отдельный по одной причине: списки
 * правил (`slop-rules.ru.ts`, `slop-rules.en.ts`) и их исполнитель
 * (`slop-check.ts`) не должны знать друг о друге. Общая форма в исполнителе
 * замкнула бы импорты в кольцо.
 *
 * Про `\b`. Все источники этой проверки написаны на Python, где `\b` знает
 * юникод. В JavaScript `\b` живёт по ASCII: `\bчестн` не совпадёт ни разу,
 * потому что перед «ч» стоит пробел, а сама «ч» для движка не буква. Перенести
 * такое выражение дословно — значит выпустить правило, которое всегда молчит.
 * Поэтому границы здесь заданы просмотром вперёд и назад по `\p{L}\p{N}`.
 */
import type { SlopSeverityV1 } from '../brand-voice/voice-wiring.contract';

/** Буква или цифра любого алфавита. */
export const WORD_CHAR = '[\\p{L}\\p{N}]';

/** Левая граница слова. Замена ASCII-`\b` там, где слово русское. */
export const LEFT = `(?<!${WORD_CHAR})`;

/** Правая граница слова. */
export const RIGHT = `(?!${WORD_CHAR})`;

/**
 * «ё» в правиле не должна решать судьбу находки: человек пишет и «надёжный»,
 * и «надежный», и оба раза это оценка вместо факта.
 */
export const yo = (source: string): string => source.replace(/ё/g, '[её]');

/** Список слов и оборотов как одно выражение с границами слова. */
export const phrases = (list: readonly string[], flags = 'giu'): RegExp =>
  new RegExp(`${LEFT}(?:${list.map(yo).join('|')})${RIGHT}`, flags);

/**
 * Что именно измеряется, когда правило считает, а не ищет.
 *
 * `count-over` — сколько раз оборот встретился во всём тексте;
 * `per-sentence` — сколько раз он встретился в одном предложении;
 * остальные читают готовые числа отчёта и пороги площадки.
 */
export type SlopMetricId =
  | 'count-over'
  | 'per-sentence'
  | 'questions'
  | 'emoji'
  | 'bold'
  | 'lists'
  | 'monotone'
  | 'no-short'
  | 'dash-density';

/**
 * По какому тексту гоняется правило.
 *
 * `prose` — после skip-зон: без кода, кавычек, ссылок, тегов и цитатных строк.
 * `raw` — сырой текст без одного лишь кода: правила класса A обязаны видеть
 * ссылку целиком, иначе `utm_source=chatgpt.com` от них спрячется.
 */
export type SlopRuleScope = 'prose' | 'raw';

export type SlopRule = {
  /** Устойчивый идентификатор: по нему экран называет находку. */
  id: string;
  severity: SlopSeverityV1;
  kind: 'regex' | 'metric';
  pattern?: RegExp;
  metric?: SlopMetricId;
  /** Порог для правил-счётчиков; у площадочных порог берётся из площадки. */
  threshold?: number;
  hint: { ru: string; en: string };
  /**
   * Площадки, где правило действует. Пусто — везде. В первой очереди правил
   * не сужено ни одно: площадка выражена порогами, а не отдельным списком.
   */
  platforms?: readonly string[];
  scope?: SlopRuleScope;
};
