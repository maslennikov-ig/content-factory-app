/**
 * Поиск по словам — один разбор запроса на весь раздел «Контент»
 * (`content-factory-next-odb8.4`, решение владельца 05.09.2026, вариант «а»).
 *
 * Владелец выбрал обычный текстовый поиск: по словам, быстро и дёшево.
 * Смысловой поиск остаётся открытым вопросом и здесь не начат — ничего, что
 * обещает понимание смысла, ни в запросе, ни на экране нет
 * (`docs/product/content-section-map.md`, §9.3).
 *
 * Правило одно и то же для материалов и для фактов: запрос режется на слова,
 * каждое слово обязано встретиться (И по словам), но встретиться оно может в
 * любом из полей строки (ИЛИ по полям). Так «подшипник поставщик» находит
 * текст, где одно слово в заголовке, а другое в теле, и не находит текст,
 * где есть только одно из них.
 *
 * Всё это выражается обычным Prisma `where` — `contains` с
 * `mode: 'insensitive'`. Ни сырого SQL, ни расширений Postgres:
 * `AGENTS.md` запрещает первое, а второе означало бы миграцию базы ради
 * поиска, который владелец просил сделать дёшево.
 */

/** Длина запроса, за которой поле отказывает. Столько же стоит в DTO. */
export const MAX_SEARCH_QUERY_LENGTH = 200;

/**
 * Сколько слов из запроса доходит до базы. Каждое слово — это ещё один
 * `contains` по нескольким полям, то есть ещё один проход по таблице; предел
 * держит цену запроса конечной, что бы человек ни вставил в поле.
 * Лишние слова отбрасываются молча: отказ на длинной фразе человек прочитал
 * бы как поломку, а не как правило.
 */
export const MAX_SEARCH_WORDS = 8;

/**
 * Запрос → слова. Разделителем считается всё, что не буква и не цифра, так
 * что «поставщик, подшипники» и «поставщик подшипники» — один и тот же запрос.
 * Регистр здесь не трогается: сравнение всё равно идёт `mode: 'insensitive'`,
 * а слово в исходном виде нужно подсветке на экране.
 */
export function searchWords(query: string | null | undefined): string[] {
  if (typeof query !== 'string') return [];
  return query
    .slice(0, MAX_SEARCH_QUERY_LENGTH)
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length > 0)
    .slice(0, MAX_SEARCH_WORDS);
}

type WordCondition = {
  OR: Array<Record<string, { contains: string; mode: 'insensitive' }>>;
};

/**
 * Слова и поля → кусок `where`, который вкладывается внутрь `where` рядом с
 * `organizationId`, а не вместо него. Возвращается `undefined`, когда искать
 * нечего: пустой `AND: []` Prisma принимает, но читается он как «фильтр
 * есть», а фильтра нет.
 */
export function wordsWhere(
  words: readonly string[],
  fields: readonly string[]
): { AND: WordCondition[] } | undefined {
  if (words.length === 0 || fields.length === 0) return undefined;
  return {
    AND: words.map((word) => ({
      OR: fields.map((field) => ({
        [field]: { contains: word, mode: 'insensitive' as const },
      })),
    })),
  };
}
