/**
 * Сошлось ли число из чужого поста с числом в найденной странице.
 *
 * `content-factory-next-tu3k.1`, решение владельца 06.09.2026: «числа берутся
 * только после проверки поиском, непроверенные в текст не идут». Решение
 * принимает этот файл, и принимает его детерминированно — ни одного вызова
 * модели. Спросить модель «подтверждает ли страница утверждение» значило бы
 * поставить проверку фактов на то же основание, которое она проверяет; здесь
 * же сверяется ровно одно, зато честно: то самое число.
 *
 * Нормализация нужна потому, что одно число пишут пятью способами. «4,2 млрд»
 * в посте и «4.2 billion» на странице — одно число; «4 200» с неразрывным
 * пробелом и «4200» — одно число. Поэтому из текста вынимаются числовые
 * лексемы, у них снимаются пробелы всех видов, запятая становится точкой, а
 * знаки процента и валюты отбрасываются: они уже сказаны словами утверждения.
 *
 * Сравнение — по равенству лексем, а не по вхождению подстроки. «137» не
 * подтверждает «37», и это не мелочь: подстрочное совпадение подтверждало бы
 * почти любое двузначное число почти любой страницей.
 */

/** Пробелы, которые встречаются внутри числа, — все четыре. */
const NUMBER_SPACES = /[\u0020\u00a0\u202f\u2009]/gu;

/**
 * Лексемы короче двух знаков не подтверждают ничего.
 *
 * «3» встретится на любой странице, и совпадение по нему — это не проверка, а
 * её видимость. Двузначное число, дробь и число с разрядами остаются.
 */
const MIN_TOKEN_LENGTH = 2;

const NUMBER_TOKEN = /\d[\d\u0020\u00a0\u202f\u2009.,]*/gu;

/**
 * Одна числовая лексема в общем виде: без пробелов, с точкой как разделителем
 * дробной части и без хвостовой пунктуации.
 *
 * Разделители разрядов снимаются вместе с пробелами, поэтому «4 200» и «4200»
 * дают одну лексему. Запятая внутри числа читается как дробная часть — так
 * пишут по-русски, и это тот случай, ради которого нормализация затевалась.
 */
export const normalizeNumberToken = (raw: string): string => {
  const withoutSpaces = raw.replace(NUMBER_SPACES, '');
  const withDot = withoutSpaces.replace(/,/gu, '.');
  const trimmedTail = withDot.replace(/[.]+$/u, '');
  // Ведущие нули значения не меняют: «07» и «7» — одно число.
  const withoutLeadingZeros = trimmedTail.replace(/^0+(?=\d)/u, '');
  return withoutLeadingZeros;
};

/** Все числовые лексемы текста в общем виде, без повторов. */
export const numberTokens = (text: string): string[] => {
  const found = (text || '').match(NUMBER_TOKEN) || [];
  const tokens = found
    .map(normalizeNumberToken)
    .filter((token) => token.length >= MIN_TOKEN_LENGTH);
  return [...new Set(tokens)];
};

/**
 * Подтверждает ли выдержка число утверждения.
 *
 * Достаточно одного совпавшего числа: утверждение «выручка достигла 4,2 млрд»
 * несёт ровно одно число, и требовать совпадения всех значило бы отклонять
 * «рост на 37% за 3 года» из-за срока, которого страница не повторила.
 * Утверждение без чисел не подтверждается никогда — его вообще не за что здесь
 * зацепить, и такие идут мимо этой проверки со статусом `skipped`.
 */
export const claimMatchesExcerpt = (
  claim: string,
  excerpt: string
): boolean => {
  const wanted = numberTokens(claim);
  if (!wanted.length) return false;
  const found = new Set(numberTokens(excerpt));
  return wanted.some((token) => found.has(token));
};
