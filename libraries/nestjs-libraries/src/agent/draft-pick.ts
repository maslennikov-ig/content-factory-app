/**
 * Отбор черновика по голосу: второй кандидат только если первый не прошёл.
 *
 * ## Зачем это построено измеримым, а не «улучшающим»
 *
 * Оба ресерча 27.08.2026 называют критик-и-правку единственным приёмом,
 * совместимым с обычным chat API, и оба честно говорят, что на метрике
 * авторского сходства он не проверен. PersonalBench показывает, что потолок
 * промптинга не сдвинулся: четыре способа персонализации дают 0,484–0,508 при
 * человеческом поле 0,626. Поэтому здесь нет ни одного правила, выведенного из
 * общих соображений: и точка выхода, и потолок попыток — числа, а не вкус.
 *
 * ## Чем судят и почему не вердиктом
 *
 * Замер 28.08.2026 на боевой: у всех трёх голосов нижняя граница мерки — ноль,
 * верхние — 0,25, 0,4 и 0,75. То есть «не похоже» выносится только тексту,
 * набравшему ровно ноль голосов, а между границами лежит широкая полоса «не
 * могу сказать», куда попадает от четверти до трети собственных постов автора.
 * Отбор по вердикту на такой мерке не отсеял бы почти ничего.
 *
 * Поэтому судят **числом голосов**, а точку выхода берут из калибровки этого
 * автора — `calibration.high`, ту самую, с которой мерка называет текст
 * похожим. Из константы её брать нельзя: она снимается на разборе, у трёх
 * боевых голосов различается втрое, и трек мерки прямо сейчас переснимает её
 * против генерации. Узел, читающий калиброванную точку, переживает смену мерки
 * без правок; узел с числом внутри — нет.
 *
 * ## Замер сделан, и отбор его не прошёл
 *
 * 28.08.2026, три черновика на тему на каждом из трёх корпусов: прогоны
 * `*-2026-08-27-t16` плюс `*-2026-08-28-p1` и `-p2`, 576 вызовов, $0,19 на
 * flex. Вариант `product`, обрезка 800, 16 тем; порядок черновиков усреднён по
 * всем шести перестановкам, интервал — бутстрапом по темам.
 *
 * | корпус | голоса: без отбора → с отбором | прирост по голосам | прирост по независимой мерке |
 * | --- | --- | --- | --- |
 * | owner | 0,017 → 0,043 | +0,025 (0,006…0,056) | **−0,003** (−0,016…0,009) |
 * | avetov | 0,257 → 0,369 | +0,112 (0,059…0,169) | +0,003 (−0,008…0,013) |
 * | britva | 0,651 → 0,778 | +0,127 (0,073…0,183) | **−0,004** (−0,013…0,003) |
 *
 * **По мерке, которой отбирали, прирост доказан на всех трёх корпусах. По
 * независимой мерке стенда — ни на одном, и на двух из трёх точечная оценка
 * отрицательна.** Это переподгонка к мерке: best-of-k завышает ровно ту
 * величину, по которой выбирали, и не покупает ту, которую не оптимизировали.
 *
 * Независимая мерка живёт на стенде и в продукт не входит намеренно: продукт
 * не должен уметь ею пользоваться, иначе следующий отбор будет подгоняться уже
 * под неё. Что она считает — записано в свидетельствах `pl1.33`.
 *
 * Второй довод того же: у `britva` отбор поднимает голоса варианта `none` — где
 * голоса нет вовсе — сильнее, чем у `product`. Правило работает и там, где
 * работать нечему. Проверено дважды: на прежней точке +0,189 против +0,127, на
 * нынешней +0,129 против +0,084.
 *
 * ## Цена зависит от точки, и точка с тех пор сдвинулась
 *
 * Доля черновиков, проходящих с первого раза, — это доля выше `calibration.high`,
 * то есть цена отбора меняется вместе с рабочей точкой мерки. 28.08.2026 решением
 * владельца допуск ложного приёма поднят с 5% до 15%, точка опустилась, и цена
 * упала:
 *
 * | корпус | прошло с первого, 5% | оплачено | прошло с первого, 15% | оплачено |
 * | --- | --- | --- | --- | --- |
 * | owner | 4% | ×2,88 | 13% | ×2,65 |
 * | avetov | 19% | ×2,56 | 29% | ×2,33 |
 * | britva | 56% | ×1,73 | **77%** | **×1,31** |
 *
 * На самом маленьком корпусе цена вошла в обещанные задачей «×1,2–1,5». Вывод
 * это не меняет, и в том вся суть: дешевизна отбора ничего не говорит о его
 * пользе, а польза не подтверждена независимой меркой ни на одном корпусе.
 * Число, ради которого узел стоял бы в продукте, отсутствует; число, во сколько
 * он обходится, всего лишь стало меньше.
 *
 * Отсюда `DRAFT_PICK_SHIPPED`: узел построен, измерен и не включён.
 */

/**
 * Порт: чем судить черновик, написанный этой версией голоса.
 *
 * Голосом и границами владеет разбор, а не граф, поэтому граф спрашивает их по
 * имени и не собирает мерку сам. Второй сборки у него нет намеренно: голос —
 * число относительно шеренги, и порог, снятый против одной шеренги и
 * применённый к голосу против другой, сравнивал бы две разные величины. Ошибка
 * была бы бесшумной — обе лежат в нуле-единице и обе выглядят как доля голосов.
 */
export const DRAFT_VOICE_JUDGE = 'DRAFT_VOICE_JUDGE';

export type DraftVoiceJudge = {
  /**
   * Голоса за автора у этого текста, 0…1; `null` — судить нечем.
   *
   * Обрезка внутри: точка снята на обрезанных текстах, и судить по ней
   * необрезанный черновик значило бы сравнивать две разные величины. Замер на
   * сохранённых прогонах, доля прошедших точку обрезанными и целиком: у
   * `avetov` вариант `product` — 3 из 16 против 1 из 16, у `britva` вариант
   * `no-portrait` — 5 из 16 против 11 из 16. Это не округление.
   */
  score(text: string): number | null;
  /** Точка, с которой мерка называет текст похожим на этого автора. */
  accepts: number;
};

export type DraftVoiceJudgePort = {
  draftJudge(
    organizationId: string,
    versionId: string
  ): Promise<DraftVoiceJudge | null>;
};

/**
 * Потолок числа попыток, и он же граница расхода.
 *
 * Три, потому что четвёртая попытка не покупает ничего, что можно назвать
 * числом: при доле прохождения 12–44% вероятность, что четвёртый черновик
 * пройдёт после трёх непрошедших, лежит там же, где и третьего, а платит за неё
 * пользователь. Каждый лишний черновик — деньги пользователя, поэтому потолок
 * стоит здесь один раз и читается обоими путями: и графом, и стендом.
 *
 * Худший случай назван прямо: ×3 к цене генерации контента. Хук оплачивается
 * один раз на все попытки — он не переписывается, отбор судит целый пост с тем
 * же хуком.
 */
export const MAX_DRAFT_ATTEMPTS = 3;

/**
 * Включён ли отбор в продукте. Нет — и теперь по измеренной причине.
 *
 * Замер 28.08.2026 (таблица выше) назвал оба числа. Отбор стоит ×1,3–2,7 к цене
 * генерации контента и покупает доказанный прирост **только по той мерке, по
 * которой отбирает**; независимая мерка его не подтверждает ни на одном из трёх
 * корпусов и на двух из трёх показывает знак в другую сторону.
 *
 * Это не «пока не измерили». Это измерено, и ответ отрицательный: правило
 * выбирает удачную выборку той же мерки, а не текст, который ближе к автору.
 * Отгружать его значило бы брать с человека вдвое за рост числа на экране.
 *
 * Код оставлен, а не удалён, по одной причине: узел читает калиброванную точку
 * из разбора, а не константу, и переживёт смену мерки. `pl1.5` эту мерку сейчас
 * и переделывает; когда у неё появится независимо подтверждаемый сигнал,
 * вопрос переспрашивается одной командой — `voice-eval/draft-pick.cjs` — и
 * включение стоит одну строку здесь. До тех пор строка остаётся такой.
 */
export const DRAFT_PICK_SHIPPED = false;

/** Черновик и то, что мерка о нём сказала. */
export type DraftCandidate = {
  /** Голоса за автора; `null` — мерка судить отказалась. */
  votes: number | null;
};

/** Прошёл ли черновик точку «похоже» этого автора. */
export const draftPasses = (
  votes: number | null | undefined,
  accepts: number | null | undefined
): boolean =>
  votes !== null &&
  votes !== undefined &&
  accepts !== null &&
  accepts !== undefined &&
  votes >= accepts;

/**
 * Платить ли за ещё один черновик.
 *
 * Четыре причины остановиться, и все четыре — «дальше платить не за что»:
 * судить нечем (мерки нет), мерка промолчала об этом черновике, потолок
 * попыток исчерпан, или один из уже оплаченных кандидатов точку прошёл.
 *
 * Проверяется весь список, а не последний кандидат: правило «остановиться,
 * когда кто-то прошёл» и правило «остановиться, когда прошёл последний»
 * совпадают ровно до первой перестановки в вызывающем коде, и расхождение было
 * бы бесшумным.
 */
export function needsAnotherDraft(
  candidates: readonly DraftCandidate[],
  accepts: number | null | undefined,
  cap: number = MAX_DRAFT_ATTEMPTS
): boolean {
  if (accepts === null || accepts === undefined) return false;
  if (!candidates.length) return false;
  if (candidates.length >= cap) return false;
  if (candidates[candidates.length - 1].votes === null) return false;
  return !candidates.some((one) => draftPasses(one.votes, accepts));
}

/**
 * Лучший кандидат по голосам, а не последний.
 *
 * Последний — это тот, на котором кончился потолок, и брать его значило бы
 * выбрасывать оплаченный черновик, который мерка оценила выше. Ничья достаётся
 * раннему: доплаченный черновик должен побеждать, а не выигрывать по жребию.
 * Кандидат, о котором мерка промолчала, не обыгрывает оценённого — молчание не
 * результат.
 */
export function bestDraftIndex(candidates: readonly DraftCandidate[]): number {
  let best = 0;
  for (let index = 1; index < candidates.length; index += 1) {
    const contender = candidates[index].votes;
    const champion = candidates[best].votes;
    if (contender === null) continue;
    if (champion === null || contender > champion) best = index;
  }
  return best;
}
