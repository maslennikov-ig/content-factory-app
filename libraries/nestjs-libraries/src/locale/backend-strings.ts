export type BackendStringKey = keyof typeof CATALOG;

/**
 * Every key the catalog carries, in declaration order.
 *
 * Exported so the suite that checks all sixteen locales are filled in reads
 * the catalog itself instead of a list copied beside it: that copy had already
 * fallen behind by two keys (`email_awaiting_approval_*`), which meant a key
 * could ship missing a locale and nothing would say so.
 */
export const BACKEND_STRING_KEYS = Object.keys(CATALOG) as BackendStringKey[];

/**
 * HTML-escape a string by replacing special characters with entities.
 * Used for template parameters that will be embedded in HTML content.
 */
function htmlEscape(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function interpolate(template: string, params?: BackendStringParams): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, token) =>
    Object.prototype.hasOwnProperty.call(params, token)
      ? htmlEscape(String(params[token]))
      : match
  );
}

function lookup(key: BackendStringKey, locale: BackendLocale): string {
  const entry: Partial<BackendStringEntry> = CATALOG[key];
  return entry[locale] ?? entry[BACKEND_FALLBACK_LOCALE]!;
}

/**
 * Falls back to English whenever a key has no entry for the requested
 * locale — none currently do, every key above lists all sixteen, but the
 * fallback stays so a future partial key degrades instead of breaking.
 *
 * Parameters are HTML-escaped, because what comes back is written into an
 * email body. For a string that is NOT going into HTML — an email subject
 * line, above all — use `translateBackendText`, or an organization called
 * `Ben & Jerry's` arrives in the reader's inbox as `Ben &amp; Jerry&#39;s`.
 */
export function translateBackendString(
  key: BackendStringKey,
  locale: BackendLocale,
  params?: BackendStringParams
): string {
  return interpolate(lookup(key, locale), params);
}

/**
 * The same lookup for a plain-text destination: parameters are substituted
 * as they are, with no HTML escaping. The caller is promising the result is
 * not about to be embedded in markup.
 */
export function translateBackendText(
  key: BackendStringKey,
  locale: BackendLocale,
  params?: BackendStringParams
): string {
  if (!params) return lookup(key, locale);
  return lookup(key, locale).replace(/\{\{(\w+)\}\}/g, (match, token) =>
    Object.prototype.hasOwnProperty.call(params, token)
      ? String(params[token])
      : match
  );
}
